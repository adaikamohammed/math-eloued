/**
 * تنظيف عنوان المورد من الزوائد والأرقام الإدارية
 */
export function cleanPedagogicalTitle(rawTitle: string): string {
  if (!rawTitle) return "";
  return rawTitle
    .replace(/^الدرسs*[:\-]?s*/i, "")
    .replace(/^الموردs*\d*\s*[:\-]?s*/i, "")
    .replace(/^مذكرةs*\d*\s*[:\-]?s*/i, "")
    .replace(/^حصةs*\d*\s*[:\-]?s*/i, "")
    .trim();
}

/**
 * استنتاج التدوين الميداني الكامل لدفتر النصوص بذكاء بناء على الدفتر اليومي
 */
export function inferCahierTextesFromDiary(
  diary: DailyDiaryEntry,
  teacherFamilyName = "عدايكة"
): CahierTextesEntry {
  const title = (diary.lessonTitle || (diary as any).resourceTitle || (diary as any).title || "").trim();
  const rawType = (diary.sessionType || "").trim();
  const stages = Array.isArray(diary.stages) ? diary.stages : [];

  // 1. البحث أولاً فيما كتبه الأستاذ فعلياً في مراحل الدفتر اليومي
  const warmupStage = stages.find((s) =>
    s.label?.includes("تمهيدي") || s.label?.includes("تهيئة") || s.label?.includes("انطلاق")
  );
  const situationStage = stages.find((s) =>
    s.label?.includes("وسيطي") || s.label?.includes("وضعية") || s.label?.includes("بناء") || s.label?.includes("تعلم")
  );
  const summaryStage = stages.find((s) =>
    s.label?.includes("حوصلة") || s.label?.includes("خلاصة") || s.label?.includes("قاعدة")
  );
  const reinvestStage = stages.find((s) =>
    s.label?.includes("نهائي") || s.label?.includes("استثمار") || s.label?.includes("تقويم") || s.label?.includes("تطبيق")
  );

  // 2. البحث في معجم المعارف البيداغوجية الذكي
  let matchedData: InferredPedagogicalData | null = null;
  const searchableText = `${title} ${rawType} ${diary.field || ""} ${diary.notes || ""}`.toLowerCase();

  for (const [key, data] of Object.entries(PEDAGOGICAL_KNOWLEDGE_BASE)) {
    if (searchableText.includes(key.toLowerCase())) {
      matchedData = data;
      break;
    }
  }

  // 3. تحديد نوع الحصة والميدان والمقطع
  const isTdOrRemediation =
    rawType.includes("موجهة") ||
    rawType.includes("استدراك") ||
    rawType.includes("معالجة") ||
    rawType.toLowerCase().includes("td") ||
    title.includes("أعمال موجهة") ||
    title.includes("استدراك") ||
    title.toLowerCase().includes("td") ||
    !!matchedData?.isTdOrRemediation;

  let sessionType = matchedData?.sessionType || "درس ومورد";
  if (rawType.includes("موجهة") || rawType.toLowerCase().includes("td")) sessionType = "أعمال موجهة (TD)";
  else if (rawType.includes("استدراك") || rawType.includes("معالجة")) sessionType = "معالجة بيداغوجية";
  else if (rawType.includes("فرض")) sessionType = "فرض محروس رسمي";
  else if (rawType.includes("اختبار")) sessionType = "اختبار فصلي رسمي";
  else if (rawType.includes("إدماج")) sessionType = "إدماج جزئي";
  else if (rawType.includes("تشخيص")) sessionType = "تقويم تشخيصي";
  else if (rawType.includes("عرض حال")) sessionType = "عرض حال وظيفة منزلية";

  const field =
    diary.field ||
    matchedData?.field ||
    (title.includes("مستقيم") ||
    title.includes("مثلث") ||
    title.includes("دائرة") ||
    title.includes("تناظر") ||
    title.includes("زاوية") ||
    title.includes("رباعي") ||
    title.includes("توازي") ||
    title.includes("تعامد") ||
    title.includes("محور") ||
    title.includes("منصف")
      ? "أنشطة هندسية"
      : "أنشطة عددية");

  const section =
    matchedData?.section ||
    (field === "أنشطة هندسية"
      ? "المقطع 02: إنشاء أشكال هندسية بسيطة والتناظر المركزي"
      : "المقطع 01: العمليات على الأعداد الطبيعية والعشرية والكسور");

  // 4. استخراج أو توليد النقاط البيداغوجية الخمسة بدقة
  const cleanTitle = cleanPedagogicalTitle(title) || "حصة تعلمية مبرمجة";

  const warmup =
    warmupStage?.content?.trim() ||
    matchedData?.warmup ||
    "تذكير بالمكتسبات القبلية والتهيئة الحافزة لإرساء المورد المعرفي.";

  const proposedSituation =
    situationStage?.content?.trim() ||
    matchedData?.proposedSituation ||
    `طرح وضعية التعلم لبناء مفهوم (${cleanTitle}) ومناقشة طرائق الحل.`;

  const summary =
    summaryStage?.content?.trim() ||
    diary.concepts?.trim() ||
    matchedData?.summary ||
    `تثبيت القاعدة والخاصية الرياضية الأساسية للمورد بالدفتر المدرسي دون حشو.`;

  const reinvestment =
    reinvestStage?.content?.trim() ||
    matchedData?.reinvestment ||
    "حل تمرين تطبيقي فردي على الكراريس لتثبيت المعارف وتصويب الأخطاء الصفية.";

  const homework =
    diary.homework?.trim() ||
    matchedData?.homework ||
    "حل تمارين تطبيقية من الكتاب المدرسي لترسيخ المورد.";

  return {
    id: `cahier_inf_${diary.id || Date.now()}`,
    diaryEntryId: diary.id,
    className: diary.className,
    date: diary.date,
    dayName: diary.day,
    periodTime: diary.periodTime || "08:00 - 09:00",
    sessionType,
    field,
    section,
    weekLabel: undefined,
    resourceTitle: cleanTitle,
    warmup,
    proposedSituation,
    summary,
    reinvestment,
    homework,
    signature: `${teacherFamilyName} ✍`,
    isTdOrRemediation,
    subgroup: isTdOrRemediation ? "القسم كامل" : undefined,
    notes: diary.notes?.trim() || undefined,
    createdAt: diary.createdAt || new Date().toISOString(),
  };
}
